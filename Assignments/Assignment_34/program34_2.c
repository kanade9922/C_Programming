#include<stdio.h>

///////////////////////////////////////////////////////////////
//
// Function Name :  Display
// Description   :  Converts uppercase character to lowercase.
// Input         :  Character
// Output        :  Lowercase Character
// Author        :  Saurabh Santosh Kanade
// Date          :  30/12/2025
//
///////////////////////////////////////////////////////////////

void Display(char ch)
{
    if(ch >= 'A' && ch <= 'Z')
    {
        ch = ch + 32;   // Convert
    }

    printf("%c\n", ch);
}

///////////////////////////////////////////////////////////////
//
// Entry Point Function
//
///////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';

    printf("Enter the character : \n");
    scanf("%c", &cValue);

    Display(cValue);

    return 0;
}

