#include<stdio.h>

///////////////////////////////////////////////////////////////
//
// Function Name :  Display
// Description   :  Prints all characters from given capital 
//                  letter to 'Z'.
// Input         :  Character
// Output        :  Sequence of characters
// Author        :  Saurabh Santosh Kanade
// Date          :  04/12/2025
//
///////////////////////////////////////////////////////////////

void Display(char ch)
{
    if(ch >= 'A' && ch <= 'Z')
    {
        for(char c = ch; c <= 'Z'; c++)
        {
            printf("%c ", c);
        }
    }
    printf("\n");
}

///////////////////////////////////////////////////////////////
//
// Entry Point Function
//
///////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';

    printf("Enter the character : \n");
    scanf("%c", &cValue);

    Display(cValue);

    return 0;
}

